-- "Change my email": the new address waits here until the user opens the link sent to it.
-- Same shape as email_verification_token (only a SHA-256 hash of the token is stored), plus the
-- address being confirmed. app_user.email only changes once the link is used.
create table email_change_token (
    id         bigint generated by default as identity primary key,
    user_id    bigint       not null references app_user (id) on delete cascade,
    new_email  varchar(254) not null,
    token_hash varchar(64)  not null,
    expires_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    constraint uq_email_change_token_hash unique (token_hash)
);

create index ix_email_change_token_user on email_change_token (user_id);
