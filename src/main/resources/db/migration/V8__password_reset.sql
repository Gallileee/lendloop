-- One-time links for "forgot my password". Only a SHA-256 hash of the token is stored, so someone
-- who can read the database still can't use a link. A token is deleted when it's used, when a
-- newer link is requested, or once it has expired.
create table password_reset_token (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references app_user (id) on delete cascade,
    token_hash varchar(64) not null,
    expires_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    constraint uq_password_reset_token_hash unique (token_hash)
);

create index ix_password_reset_token_user on password_reset_token (user_id);
