-- A loan goes REQUESTED -> ACTIVE -> RETURNED, or ends as DECLINED / CANCELLED.

create table loan (
    id           bigint generated by default as identity primary key,
    item_id      bigint      not null references item (id) on delete cascade,
    borrower_id  bigint      not null references app_user (id) on delete cascade,
    status       varchar(12) not null,
    message      varchar(300),
    due_date     date,
    requested_at timestamp with time zone not null,
    decided_at   timestamp with time zone,
    returned_at  timestamp with time zone,

    -- The two rules below would be partial unique indexes ("... where status = 'ACTIVE'") on
    -- PostgreSQL, but H2 has no partial indexes. Instead these copy columns are filled only
    -- while the rule applies and are NULL otherwise; a unique constraint ignores NULLs on both.

    -- item_id while ACTIVE: an item can be lent to one person at a time.
    active_item_id           bigint,
    -- item_id and borrower_id while REQUESTED: one open request per person and item.
    open_request_item_id     bigint,
    open_request_borrower_id bigint,

    constraint ck_loan_status check (status in ('REQUESTED', 'ACTIVE', 'RETURNED', 'DECLINED', 'CANCELLED')),
    constraint ck_loan_active_due check (status <> 'ACTIVE' or due_date is not null),
    constraint uq_loan_active_item unique (active_item_id),
    constraint uq_loan_open_request unique (open_request_item_id, open_request_borrower_id)
);

create index ix_loan_item on loan (item_id);
create index ix_loan_borrower on loan (borrower_id);
