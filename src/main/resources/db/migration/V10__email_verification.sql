-- When the user proved they can read their email (a link from the sign-up email, or a password
-- reset). Null until then: reminders and notices are only emailed to confirmed addresses.
alter table app_user add column email_verified_at timestamp with time zone;

-- Accounts from before this migration have been getting emails all along; keep it that way.
update app_user set email_verified_at = created_at;

-- One-time "confirm your email" links. Same shape as password_reset_token: only a SHA-256 hash
-- of the token is stored, and a token is deleted when it's used, replaced or expired.
create table email_verification_token (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references app_user (id) on delete cascade,
    token_hash varchar(64) not null,
    expires_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    constraint uq_email_verification_token_hash unique (token_hash)
);

create index ix_email_verification_token_user on email_verification_token (user_id);
