-- Groups of friends who lend to each other. "group" is a reserved word, hence app_group.

create table app_group (
    id                bigint generated by default as identity primary key,
    name              varchar(60)  not null,
    -- Anyone with the link can join until it expires; the owner can replace it at any time.
    invite_token      varchar(64)  not null,
    invite_expires_at timestamp with time zone not null,
    created_at        timestamp with time zone not null,
    constraint uq_app_group_invite_token unique (invite_token)
);

create table group_member (
    id        bigint generated by default as identity primary key,
    group_id  bigint      not null references app_group (id) on delete cascade,
    user_id   bigint      not null references app_user (id) on delete cascade,
    role      varchar(10) not null,
    joined_at timestamp with time zone not null,
    -- Joining twice (two clicks, two tabs) can never create a second membership.
    constraint uq_group_member unique (group_id, user_id)
);

create index ix_group_member_user on group_member (user_id);
